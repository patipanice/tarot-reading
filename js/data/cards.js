function buildMinorArcana() {
  const cards = [];
  SUITS.forEach((suit) => {
    RANKS.forEach((r) => {
      const id = `minor-${suit.id}-${r.rank}`;
      const rankLabel = r.rank === "ace" ? "เอซ" : r.rank === "page" ? "เพจ" : r.rank === "knight" ? "อัศวิน" : r.rank === "queen" ? "ควีน" : r.rank === "king" ? "คิง" : r.nameTh;
      cards.push({
        id,
        nameTh: `${rankLabel}${["page","knight","queen","king"].includes(r.rank) ? "" : "แห่ง"}${suit.nameTh}`,
        nameEn: `${r.rank} of ${suit.id}`,
        arcana: "minor",
        suit: suit.id,
        image: `${id}.jpg`,
        keywordsUpright: [r.upright],
        keywordsReversed: [r.reversed],
        meaningUpright: `เกี่ยวข้องกับ${suit.theme} — ${r.upright}`,
        meaningReversed: `เกี่ยวข้องกับ${suit.theme} — ${r.reversed}`
      });
    });
  });
  return cards;
}

